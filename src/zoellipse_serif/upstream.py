"""Load the Source Serif 4 Text masters as a designspace of in-memory UFOs.

Adobe's masters keep their OpenType code in .fea files included from outside
the UFO (makeotf layout). Only the GSUB code (familyGSUB.fea) and the three
contextual kerning rules are kept, inlined into each UFO; mark, mkmk and kern
are generated by ufo2ft from the UFOs' anchors and kerning, so they follow the
transformed outlines. Name, OS/2, hhea, BASE and STAT come from build.py/meta.py.
"""
import re

import ufoLib2
from fontTools.designspaceLib import AxisDescriptor, DesignSpaceDocument, InstanceDescriptor, SourceDescriptor

from . import archaic
from . import params as P

KERN_CTXT = {False: "Roman/Instances/Text/Regular/kern_ctxt.fea",
             True: "Italic/Instances/Text/It/kern_ctxt.fea"}
WEIGHTS = ["ExtraLight", "Light", "Regular", "Medium", "SemiBold", "Bold", "ExtraBold", "Black"]


def load(italic):
    slope = P.UPSTREAM / P.SLOPES[italic]
    ds = DesignSpaceDocument()
    ds.addAxis(AxisDescriptor(tag="wght", name="Weight", minimum=0, default=P.MASTER_DESIGN[1],
                              maximum=1000))
    fea = features(italic)
    ufos = [ufoLib2.Font.open(slope / rel) for rel in P.MASTERS[italic]]
    archaic.add(ufos, italic)
    for ufo, d, style in zip(ufos, P.MASTER_DESIGN, P.MASTER_STYLE):
        clean(ufo)
        ufo.features.text = fea
        ufo.info.styleName = style + (" Italic" if italic else "")
        ds.addSource(SourceDescriptor(font=ufo, location={"Weight": d}, styleName=ufo.info.styleName,
                                      familyName=P.FAMILY))
    for w in WEIGHTS:          # locations are set by weights.match
        style = (w + " Italic" if w != "Regular" else "Italic") if italic else w
        ds.addInstance(InstanceDescriptor(familyName=P.FAMILY, styleName=style,
                                          location={"Weight": P.MASTER_DESIGN[1]}))
    return ds


def features(italic):
    gsub = (P.UPSTREAM / P.SLOPES[italic] / "familyGSUB.fea").read_text()
    # the italic's ss03 (alternate ampersand) has no UI name upstream
    gsub = gsub.replace("feature ss03 {\n", 'feature ss03 {\n    featureNames { name "Alternate ampersand"; };\n', 1)
    ctxt = (P.UPSTREAM / KERN_CTXT[italic]).read_text()
    return (gsub + "\n\nfeature kern {\n    # Automatic Code\n" + ctxt.strip() + "\n} kern;\n")


def clean(ufo):
    """Drop Adobe's processed-glyphs layer and kerning that points at undefined groups."""
    for name in [layer.name for layer in ufo.layers if layer is not ufo.layers.defaultLayer]:
        del ufo.layers[name]
    groups = set(ufo.groups)
    for pair in list(ufo.kerning):
        if any(side.startswith("public.kern") and side not in groups for side in pair):
            del ufo.kerning[pair]
    for key in [k for k in ufo.lib if re.match(r"com\.adobe\.", k)]:
        del ufo.lib[key]
